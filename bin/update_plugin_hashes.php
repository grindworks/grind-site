<?php

/**
 * update_plugin_hashes.php
 *
 * Write src/lib/bundled_plugin_hashes.php: the SHA-256 of every version of each
 * bundled plugin that has been committed, plus the current working copy.
 *
 * Enabling a plugin renames _foo.php to foo.php, and updates only replace _foo.php.
 * grinds_sync_bundled_plugins() uses this list to replace an enabled copy with the
 * new bundled version only when the copy is an unmodified earlier release.
 *
 * Usage: php bin/update_plugin_hashes.php   (run from the repository root)
 */

declare(strict_types=1);

$root = dirname(__DIR__);
$pluginDir = $root . '/src/plugins';
$outFile = $root . '/src/lib/bundled_plugin_hashes.php';

chdir($root);

$hashes = [];
foreach (glob($pluginDir . '/_*.php') as $file) {
    $name = substr(basename($file), 1);
    $rel = 'src/plugins/' . basename($file);
    $set = [hash_file('sha256', $file) => true];

    // Each commit that touched the file, with the path it had in that commit
    $log = (string)shell_exec('git log --follow --name-only --format=%H -- ' . escapeshellarg($rel));
    $lines = array_values(array_filter(array_map('trim', explode("\n", $log)), 'strlen'));
    for ($i = 0; $i + 1 < count($lines); $i += 2) {
        $commit = $lines[$i];
        $path = $lines[$i + 1];
        if (!preg_match('/^[0-9a-f]{40}$/', $commit)) {
            fwrite(STDERR, "Unexpected git log output near: {$commit}\n");
            exit(1);
        }
        $blob = shell_exec('git show ' . escapeshellarg($commit . ':' . $path) . ' 2>/dev/null');
        if (is_string($blob) && $blob !== '') {
            $set[hash('sha256', $blob)] = true;
        }
    }

    $hashes[$name] = array_keys($set);
    sort($hashes[$name]);
}
ksort($hashes);

$out = "<?php\n\n/**\n * bundled_plugin_hashes.php\n *\n * SHA-256 of every released version of each bundled plugin, keyed by the enabled file name.\n * Generated by bin/update_plugin_hashes.php. Do not edit by hand.\n */\nif (!defined('GRINDS_APP')) exit;\n\nreturn [\n";
foreach ($hashes as $name => $list) {
    $out .= "    " . var_export($name, true) . " => [\n";
    foreach ($list as $h) {
        $out .= "        '{$h}',\n";
    }
    $out .= "    ],\n";
}
$out .= "];\n";

file_put_contents($outFile, $out);
echo "Wrote " . count($hashes) . " plugins to " . substr($outFile, strlen($root) + 1) . "\n";
